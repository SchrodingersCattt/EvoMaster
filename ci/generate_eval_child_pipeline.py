#!/usr/bin/env python3
"""Scan evaluation/question_bank/ and generate a dynamic child pipeline YAML.

Reads every ``*.yaml`` file under the question bank directory, extracts the
top-level ``capability`` field, deduplicates and sorts them, then emits a
GitLab CI child pipeline with one manual job per capability.

Output: ``ci/generated-eval-child.yml`` (overwritten each run).

Usage (CI or local)::

    pip install pyyaml
    python ci/generate_eval_child_pipeline.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
QUESTION_BANK_DIR = REPO_ROOT / "evaluation" / "question_bank"
OUTPUT_PATH = REPO_ROOT / "ci" / "generated-eval-child.yml"


def discover_capabilities(bank_dir: Path) -> list[str]:
    """Return sorted unique capabilities found in question bank YAML files."""
    caps: set[str] = set()
    for yaml_file in sorted(bank_dir.rglob("*.yaml")):
        if yaml_file.name == "manifest.yaml":
            continue
        try:
            data = yaml.safe_load(yaml_file.read_text(encoding="utf-8"))
        except Exception:
            continue
        if isinstance(data, dict) and data.get("capability"):
            caps.add(str(data["capability"]).strip())
    return sorted(caps)


# ---------------------------------------------------------------------------
# YAML generation helpers — we emit plain text to keep full control over
# formatting and avoid PyYAML quoting surprises in shell blocks.
# ---------------------------------------------------------------------------

HEADER = """\
# AUTO-GENERATED by ci/generate_eval_child_pipeline.py — DO NOT EDIT
#
# 动态评测子流水线：每个 capability 一个手动触发的评测 job。
# 由 baseline-eval.yml 的 baseline-eval-trigger 触发。
# 变量（EVAL_RUNNER、ANTHROPIC_*、LITELLM_*、BASELINE_*、DYNAMIC_IMAGE 等）从父流水线继承。

stages:
  - init
  - eval
"""

INIT_JOB_TEMPLATE = """\

child-pipeline-ready:
  stage: init
  image: alpine:latest
  script:
    - echo "=== 子流水线就绪 ==="
    - echo "评测引擎：${{EVAL_RUNNER:-claude_cli}}"
    - echo "镜像    ：${{DYNAMIC_IMAGE:-<未传入>}}"
    - echo "模型    ：${{BASELINE_MODEL:-<默认>}}"
    - echo "模式    ：${{BASELINE_MODES:-direct}}"
    - echo "每类题数限制：${{BASELINE_LIMIT:-0}}"
    - echo ""
    - echo "检测到 {cap_count} 个 capability：{cap_list}"
    - echo "请在下方手动触发需要评测的 capability job。"
  tags:
    - k8s-runner-ack
"""

EVAL_TEMPLATE = """\

.eval-template:
  stage: eval
  image: $REGISTRY/public/ubuntu:gitlab-docker
  variables:
    DOCKER_HOST: tcp://docker-build-service:32375
  when: manual
  allow_failure: true
  timeout: 4h
  before_script:
    - |
      cat > /root/.docker/config.json <<EOF
      {
        "auths": {
          "registry.dp.tech": {
            "auth": "$(echo -n ${REGISTRY_USERNAME}:${REGISTRY_PASSWORD} | base64)"
          }
        }
      }
      EOF
    - docker pull "${DYNAMIC_IMAGE}"
  script:
    - |
      RUNNER_NAME="eval-${EVAL_CAP}-runner"
      docker rm -f "${RUNNER_NAME}" 2>/dev/null || true
      docker create --name "${RUNNER_NAME}" \\
        -e EVAL_RUNNER \\
        -e ANTHROPIC_API_KEY \\
        -e ANTHROPIC_AUTH_TOKEN \\
        -e ANTHROPIC_BASE_URL \\
        -e ANTHROPIC_MODEL \\
        -e ANTHROPIC_DEFAULT_HAIKU_MODEL \\
        -e ANTHROPIC_DEFAULT_OPUS_MODEL \\
        -e ANTHROPIC_DEFAULT_SONNET_MODEL \\
        -e MATMASTER_TOOLS_SERVER \\
        -e MATMASTER_TOOLS_EVALUATION_BEARER \\
        -e LITELLM_PROXY_API_KEY \\
        -e LITELLM_PROXY_API_BASE \\
        -e BASELINE_CAPABILITIES="${EVAL_CAP}" \\
        -e BASELINE_MODES="${BASELINE_MODES}" \\
        -e BASELINE_LIMIT="${BASELINE_LIMIT}" \\
        -e BASELINE_MAX_TURNS="${BASELINE_MAX_TURNS}" \\
        -e BASELINE_TIMEOUT="${BASELINE_TIMEOUT}" \\
        -e BASELINE_MODEL="${BASELINE_MODEL}" \\
        -e BASELINE_RUN_LABEL="${BASELINE_RUN_LABEL}_${EVAL_CAP}" \\
        -e BASELINE_PENDING_ONLY="${BASELINE_PENDING_ONLY}" \\
        "${DYNAMIC_IMAGE}" \\
        bash /app/ci/run_baseline_eval.sh
      EVAL_EXIT=0
      docker start -a "${RUNNER_NAME}" || EVAL_EXIT=$?
      echo "[CI] 容器退出码: ${EVAL_EXIT}"
      docker cp "${RUNNER_NAME}:/app/results" "./ci_results_${EVAL_CAP}" || true
      docker cp "${RUNNER_NAME}:/app/baseline_run.env" "./baseline_run_${EVAL_CAP}.env" || true
      docker rm "${RUNNER_NAME}" || true
      exit ${EVAL_EXIT}
  after_script:
    - docker rm -f "eval-${EVAL_CAP}-runner" 2>/dev/null || true
  artifacts:
    paths:
      - ci_results_${EVAL_CAP}/
      - baseline_run_${EVAL_CAP}.env
    expire_in: 30 days
    when: always
  tags:
    - k8s-runner-ack
"""

CAP_JOB_TEMPLATE = """\

eval-{cap}:
  extends: .eval-template
  variables:
    EVAL_CAP: {cap}
"""


def generate(caps: list[str]) -> str:
    parts: list[str] = [HEADER]
    parts.append(
        INIT_JOB_TEMPLATE.format(
            cap_count=len(caps),
            cap_list=", ".join(caps),
        )
    )
    parts.append(EVAL_TEMPLATE)
    for cap in caps:
        parts.append(CAP_JOB_TEMPLATE.format(cap=cap))
    return "".join(parts)


def main() -> int:
    if not QUESTION_BANK_DIR.is_dir():
        print(
            f"Error: question bank dir not found: {QUESTION_BANK_DIR}", file=sys.stderr
        )
        return 1

    caps = discover_capabilities(QUESTION_BANK_DIR)
    if not caps:
        print("Error: no capabilities found in question bank", file=sys.stderr)
        return 1

    print(f"Discovered {len(caps)} capabilities: {', '.join(caps)}", file=sys.stderr)

    content = generate(caps)
    OUTPUT_PATH.write_text(content, encoding="utf-8")
    print(f"Generated: {OUTPUT_PATH}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
