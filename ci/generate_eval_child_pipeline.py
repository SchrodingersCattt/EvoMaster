#!/usr/bin/env python3
"""Scan evaluation/question_bank/ and generate a dynamic child pipeline YAML.

Modes (see ``ci/baseline_eval_preset.yaml`` and env ``BASELINE_CHILD_PIPELINE``):

* ``capabilities`` (default): one manual job per capability discovered in the bank.
* ``questions``: a single job ``eval-question-list`` (runs automatically after
  ``child-pipeline-ready``); IDs from the preset or ``BASELINE_QUESTIONS``
  (comma-separated), or at job runtime when ``questions_mode`` is
  ``score_summary_missing_cc`` (empty ``question_ids`` allowed). No per-capability jobs.

Output: ``ci/generated-eval-child.yml`` (overwritten each run).

Usage (CI or local)::

    pip install pyyaml
    python ci/generate_eval_child_pipeline.py
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

import yaml

_PRESET_MOD_PATH = Path(__file__).resolve().parent / "baseline_eval_preset.py"
_spec = importlib.util.spec_from_file_location("baseline_eval_preset", _PRESET_MOD_PATH)
assert _spec and _spec.loader
baseline_eval_preset = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(baseline_eval_preset)

REPO_ROOT = Path(__file__).resolve().parent.parent
QUESTION_BANK_DIR = REPO_ROOT / "evaluation" / "question_bank"
OUTPUT_PATH = REPO_ROOT / "ci" / "generated-eval-child.yml"


def discover_capabilities(bank_dir: Path) -> list[str]:
    """Return sorted unique capabilities found in question bank YAML files."""
    caps: set[str] = set()
    for yaml_file in sorted(bank_dir.rglob("*.yaml")):
        if yaml_file.name == "manifest.yaml":
            continue
        try:
            data = yaml.safe_load(yaml_file.read_text(encoding="utf-8"))
        except Exception:
            continue
        if isinstance(data, dict) and data.get("capability"):
            caps.add(str(data["capability"]).strip())
    return sorted(caps)


