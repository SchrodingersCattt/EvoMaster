def generate_capabilities(caps: list[str]) -> str:
    parts: list[str] = [HEADER_CAPABILITIES]
    parts.append(
        INIT_JOB_TEMPLATE.format(
            cap_count=len(caps),
            cap_list=", ".join(caps),
        )
    )
    parts.append(EVAL_TEMPLATE)
    for cap in caps:
        parts.append(CAP_JOB_TEMPLATE.format(cap=cap))
    return "".join(parts)


def generate_questions() -> str:
    # INIT_JOB_* 里用 {{ }} 是为了 str.format 转义成单层 { }；此处必须 .format()，否则会生成
    # ${{VAR}} 字面量，Alpine sh 报 bad substitution。
    parts: list[str] = [
        HEADER_QUESTIONS,
        INIT_JOB_QUESTIONS_TEMPLATE.format(),
        QUESTIONS_EVAL_JOB,
    ]
    return "".join(parts)


def main() -> int:
    mode = baseline_eval_preset.resolve_child_pipeline()
    print(f"Child pipeline layout: {mode}", file=sys.stderr)

    if mode == "questions":
        qm = baseline_eval_preset.resolve_questions_mode()
        qids = baseline_eval_preset.resolve_question_ids()
        if not qids and qm != "score_summary_missing_cc":
            print(
                "Error: child_pipeline=questions requires non-empty question_ids in "
                "ci/baseline_eval_preset.yaml or BASELINE_QUESTIONS (comma-separated) "
                "in CI variables (unless questions_mode is score_summary_missing_cc).",
                file=sys.stderr,
            )
            return 1
        if qids:
            print(f"Question list ({len(qids)}): {', '.join(qids)}", file=sys.stderr)
        else:
            print(
                "questions_mode=score_summary_missing_cc: ids resolved at job runtime "
                "from score-summary (optional intersect with preset when non-empty).",
                file=sys.stderr,
            )
        content = generate_questions()
    else:
        if not QUESTION_BANK_DIR.is_dir():
            print(
                f"Error: question bank dir not found: {QUESTION_BANK_DIR}",
                file=sys.stderr,
            )
            return 1

        caps = discover_capabilities(QUESTION_BANK_DIR)
        if not caps:
            print("Error: no capabilities found in question bank", file=sys.stderr)
            return 1

        print(
            f"Discovered {len(caps)} capabilities: {', '.join(caps)}", file=sys.stderr
        )
        content = generate_capabilities(caps)

    OUTPUT_PATH.write_text(content, encoding="utf-8")
    print(f"Generated: {OUTPUT_PATH}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
